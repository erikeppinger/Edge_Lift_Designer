// Builds js/bambu-presets.js from an installed Bambu Studio's system profiles:
//   node tools/bambu-presets.mjs "%APPDATA%/BambuStudio/system/BBL"
// Bambu Studio only applies the per-object settings of a 3MF that names its printer, process and
// filament presets, so the app needs the exact preset names per printer and nozzle.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
const read = (sub, name) => JSON.parse(readFileSync(join(dir, sub, name + ".json"), "utf8"));
const field = (sub, name, key) => {
  for (let n = name, i = 0; n && i < 10; i++) {
    const j = read(sub, n);
    if (j[key] !== undefined) return j[key];
    n = j.inherits;
  }
  return undefined;
};
const out = {};
for (const f of readdirSync(join(dir, "machine")).filter((f) => /^Bambu Lab .* nozzle\.json$/.test(f)).sort()) {
  const name = f.slice(0, -5);
  const model = field("machine", name, "printer_model");
  const nozzle = field("machine", name, "nozzle_diameter")?.[0];
  const print = field("machine", name, "default_print_profile");
  let filament = field("machine", name, "default_filament_profile");
  if (Array.isArray(filament)) filament = filament[0];
  if (!model || !nozzle || !print || !filament) continue;
  (out[model] ??= {})[nozzle] = { printer: name, print, filament };
}
writeFileSync(new URL("../js/bambu-presets.js", import.meta.url),
  `// Generated by tools/bambu-presets.mjs from Bambu Studio's system profiles. Do not edit by hand.\n` +
  `export const BAMBU_PRESETS = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(out).length, "printers", JSON.stringify(out["Bambu Lab A1"]));
